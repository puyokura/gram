pub(crate) fn builtin_action_localization(action_id: &str, locale: &str) -> Option<ActionLocalization> {
    let entry = BUILTIN_ACTIONS.iter().find(|entry| entry.action_id == action_id)?;
    let is_ja = locale == "ja" || locale.starts_with("ja-");
    if is_ja {
        Some(ActionLocalization {
            label: Arc::from(entry.ja_label),
            description: Some(Arc::from(entry.ja_description)),
            keywords: entry.ja_keywords.iter().map(|kw| Arc::from(*kw)).collect(),
        })
    } else {
        Some(ActionLocalization {
            label: Arc::from(entry.en_label),
            description: Some(Arc::from(entry.en_description)),
            keywords: Vec::new(),
        })
    }
}
